#include "xanatoo/source_view.hpp"

#include "xanatoo/parse.hpp"

#include <stdexcept>

namespace xanatoo {

namespace {

// At most this many nodes are named; the rest are counted.
constexpr size_t kListedNodes = 5;
constexpr size_t kExcerptBytes = 60;

std::string excerpt(const Node& n) {
  std::string text;
  for (const InlineSpan& sp : n.spans) {
    if (!text.empty()) text += ' ';
    text += sp.text.empty() ? sp.href : sp.text;
    if (text.size() > kExcerptBytes) break;
  }
  if (text.size() > kExcerptBytes) {
    size_t cut = kExcerptBytes;
    while (cut > 0 && (static_cast<unsigned char>(text[cut]) & 0xC0) == 0x80)
      --cut;  // keep UTF-8 sequences whole
    text.resize(cut);
    text += "…";
  }
  return text;
}

}  // namespace

std::string unwritten_spans_warning(const Document& doc,
                                    const std::vector<NodeId>& nodes) {
  if (nodes.empty()) return {};
  std::string out = "Invalid document structure: " + std::to_string(nodes.size()) +
      (nodes.size() == 1 ? " node holds" : " nodes hold") +
      " inline text where this format allows none; it is left out below:";
  for (size_t i = 0; i < nodes.size() && i < kListedNodes; ++i) {
    const Node& n = doc.get(nodes[i]);
    out += "\n• <";
    out += xml_element_name(n);
    out += "> #" + std::to_string(n.id) + ": " + excerpt(n);
  }
  if (nodes.size() > kListedNodes)
    out += "\n• … and " + std::to_string(nodes.size() - kListedNodes) + " more";
  return out;
}

SourceViewText source_view_text(const Document& doc, SelectorKind kind,
                                std::optional<std::string_view> raw) {
  std::vector<NodeId> unwritten;
  switch (kind) {
    case SelectorKind::SourceRaw:
      return {raw ? std::string(*raw)
                  : "Raw source is unavailable for this document.\n"
                    "The page was generated by an importer or service adapter.\n",
              "text", {}};
    case SelectorKind::SourceSexpr: {
      std::string text = serialize_sexpr(doc, &unwritten);
      return {std::move(text), "lisp", unwritten_spans_warning(doc, unwritten)};
    }
    case SelectorKind::SourceXml: {
      std::string text = serialize_xml(doc, &unwritten);
      return {std::move(text), "xml", unwritten_spans_warning(doc, unwritten)};
    }
    default:
      throw std::invalid_argument("not a source pipe");
  }
}

Document source_view_document(const SourceViewText& source) {
  Document doc;
  const NodeId root = doc.create(NodeKind::Document);
  if (!source.warning.empty()) {
    const NodeId note = doc.create(NodeKind::Note, root);
    doc.get(note).src = "warning";
    doc.append_text(note, source.warning);
  }
  const NodeId code = doc.create(NodeKind::CodeBlock, root);
  doc.get(code).src = source.language;
  doc.append_text(code, source.text);
  return doc;
}

}  // namespace xanatoo
